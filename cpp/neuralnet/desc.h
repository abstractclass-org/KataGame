struct ValueHeadDesc {
  std::string name;
  int modelVersion;
  ConvLayerDesc v1Conv;
  BatchNormLayerDesc v1BN;
  ActivationLayerDesc v1Activation;
  MatMulLayerDesc v2Mul;
  MatBiasLayerDesc v2Bias;
  ActivationLayerDesc v2Activation;
  MatMulLayerDesc v3Mul;
  MatBiasLayerDesc v3Bias;
  MatMulLayerDesc sv3Mul;
  MatBiasLayerDesc sv3Bias;
  ConvLayerDesc vOwnershipConv;

  //Enclosure fork (owner, 2026-10-04): the training-only outputs, exported. Version 17's first value-head option
  //holds the aux version (0: none). All raw, from the player to move's view, scaled like the other outputs
  //(ModelPostProcessParams::outputScaleMultiplier).
  int auxVersion;
  ConvLayerDesc auxTrunkConv;    //trunk -> 8: the 2 future positions, the 2 territory incomes, the 4 cut-edge logits
  ConvLayerDesc auxScoringConv;  //v1 -> 1: the future occupancy (KataGo's scoring head)
  MatMulLayerDesc auxValueMul;   //v2 -> 12: the misc value outputs 4-9 and the more-misc 2-7 (TD values and scores)
  MatBiasLayerDesc auxValueBias;
  std::vector<RegretHeadDesc> regretHeads;  //none, 2: the regret value, then the regret ranking, or 4: then the swing
                                            //value and the swing ranking (Enclosure fork, 2026-10-11)
  //Export stage 2 (aux version 2): the score belief (model_pytorch.ValueHead.forward), scoreBeliefLen bins of
  //scoreBinWidth points, centred (bin i's centre is (i - len/2 + 0.5) bins). The backend computes sbS2 and sbMix
  //from the pooled v1 features; NNEvaluator finishes the mixture (NNEvaluator::finishScoreBelief).
  int scoreBeliefLen;
  float scoreBinWidth;
  float scoreOffsetScale;          //the offset feature: scoreOffsetScale * (i - len/2 + 0.5)
  MatMulLayerDesc sbS2Mul;         //pooled v1 -> c_sv2
  MatBiasLayerDesc sbS2Bias;
  MatMulLayerDesc sbS2OffMul;      //the offset feature (1) -> c_sv2
  MatMulLayerDesc sbS3Mul;         //c_sv2 -> the mixture's components
  MatBiasLayerDesc sbS3Bias;
  MatMulLayerDesc sbMixMul;        //pooled v1 -> the components' log weights
  MatBiasLayerDesc sbMixBias;

  ValueHeadDesc();
  ~ValueHeadDesc();
  ValueHeadDesc(std::istream& in, int modelVersion, bool binaryFloats);
  ValueHeadDesc(ValueHeadDesc&& other);

  ValueHeadDesc(const ValueHeadDesc&) = delete;
  ValueHeadDesc& operator=(const ValueHeadDesc&) = delete;

  ValueHeadDesc& operator=(ValueHeadDesc&& other);

  void iterConvLayers(const std::function<void(const ConvLayerDesc& dest)>& f) const;
  int64_t getNumParameters() const;

  void transformToReduceActivations();
  void applyScale8ToReduceActivations();

  void releaseWeights();
};

